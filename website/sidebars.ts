import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

// The site has three sidebars. Each category takes its pages from one directory under `docs/`,
// in the order of their `sidebar_position`. In the `reference` tree, the `index.md` of a
// directory is the page of its category, and `_category_.json` gives its label and position.
const dir = (label: string, dirName: string, collapsed = true) => ({
  type: 'category' as const,
  label,
  collapsed,
  link: { type: 'generated-index' as const, slug: `/${dirName}` },
  items: [{ type: 'autogenerated' as const, dirName }],
});

const sidebars: SidebarsConfig = {
  guide: [
    'intro',
    'concepts',
    dir('Getting started', 'getting-started', false),
    dir('Architecture', 'architecture'),
    dir('Agents', 'agents'),
    dir('Desktop app and UI', 'desktop'),
    dir('Using neohar', 'guides'),
    dir('Testing and quality', 'testing'),
  ],
  api: [{ type: 'autogenerated', dirName: 'reference' }],
  crates: [{ type: 'autogenerated', dirName: 'code' }],
};

export default sidebars;
