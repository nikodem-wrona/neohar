/// Whether the name of a script or a target is a test, a lint or a build: `test`, `test:unit`,
/// `build-all`, `lint_fix`.
pub(super) fn is_runner_name(name: &str) -> bool {
    let first = name
        .split([':', '-', '_', '.', '/'])
        .next()
        .unwrap_or(name)
        .to_ascii_lowercase();
    RUNNER_WORDS.contains(&first.as_str())
}
